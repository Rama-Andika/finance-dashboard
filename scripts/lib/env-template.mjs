import { randomBytes } from 'node:crypto'
import { CLIENT_ID_PATTERN } from './env-rules.mjs'

/** A new random SESSION_SECRET: 32 random bytes as 64 hexadecimal characters. */
export function newSessionSecret() {
  return randomBytes(32).toString('hex')
}

/**
 * The text of a new environment file for one deployment. DATABASE_URL is left empty on purpose: scripts/ops/env-check.mjs
 * refuses the file until the owner has filled it in, so no example value can end up on a server.
 * @param {{ client: string, env: string, port: number, secret: string, timezone?: string }} options
 *   client: the client name as used in the folder name (for staging the CLIENT_ID becomes "<client>-staging").
 */
export function buildEnvFileText({ client, env, port, secret, timezone = 'Asia/Jakarta' }) {
  if (!CLIENT_ID_PATTERN.test(client))
    throw new Error('client must be lowercase letters, digits and dashes (at most 64 characters)')
  if (env !== 'staging' && env !== 'production') throw new Error('env must be staging or production')
  if (!Number.isInteger(port) || port < 1024 || port > 65535)
    throw new Error('port must be a whole number from 1024 to 65535')
  if (secret.length < 32) throw new Error('the secret must be at least 32 characters')
  try {
    new Intl.DateTimeFormat('en-US', { timeZone: timezone })
  } catch {
    throw new Error('timezone is not a valid time zone name (for example Asia/Jakarta)')
  }
  const clientId = env === 'staging' ? `${client}-staging` : client
  return (
    [
      `# Settings of one deployment of the Oxy Finance Dashboard: ${env}, client ${client}.`,
      '# Loaded by systemd (EnvironmentFile=), never by the application itself.',
      '# Check it before every start: node scripts/ops/env-check.mjs <this file>',
      '# One KEY=value per line, no spaces around the =, comments on their own line. Keep the file readable by its owner only (mode 600).',
      '',
      `APP_ENV=${env}`,
      'NODE_ENV=production',
      `CLIENT_ID=${clientId}`,
      `PORT=${port}`,
      'HOST=127.0.0.1',
      'TRUST_PROXY=1',
      `TZ=${timezone}`,
      `APP_TIMEZONE=${timezone}`,
      '',
      '# Fill in: mysql://USER:PASSWORD@HOST:PORT/DATABASE (the database of this deployment only).',
      'DATABASE_URL=',
      '',
      '# Generated by init-env. Never reuse it for another deployment. Replacing it signs every user out.',
      `SESSION_SECRET=${secret}`,
      '',
      '# 0: the deploy script applies the dash_* migrations before it switches to a new release. 1 would also apply them when the server starts.',
      'AUTO_MIGRATE=0',
      '',
      '# An absolute folder outside the release folders, so the logs survive a release. It must exist and belong to the user that runs the app.',
      '# LOG_DIR=/absolute/path/to/logs',
      'LOG_LEVEL=info',
    ].join('\n') + '\n'
  )
}

/**
 * The same text with a new SESSION_SECRET. Exactly one SESSION_SECRET line must exist; every other line stays as it was.
 * @param {string} text
 * @param {string} secret
 */
export function replaceSessionSecret(text, secret) {
  const pattern = /^SESSION_SECRET=.*$/gm
  const count = (text.match(pattern) ?? []).length
  if (count !== 1) throw new Error(`expected exactly one SESSION_SECRET line, found ${count}`)
  return text.replace(pattern, () => `SESSION_SECRET=${secret}`)
}
